#!/usr/bin/env python3
"""Integrality test by initial forms ("no point at infinity in residue characteristic p").

Let G be polynomials with integer coefficients in torus variables y (every solution has all y_i != 0), all lying in
the ideal of the system (or vanishing on its solutions).  Let v be a discrete valuation on a field L, with residue
field of characteristic p, and xi in (L^*)^n a common zero of G.  Put w = v(xi) and xi0 = the residues of
xi_i / pi^{w_i}.  For each g in G the terms of minimal w-weight cancel, so in_w(g)(xi0) = 0 (min convention; the
coefficients are reduced mod p and are units, which is checked).  Hence w lies in the tropical prevariety of G, and
the initial system {in_w(g)} has a zero in the torus over the algebraic closure of F_p.
gfan uses the max convention: a gfan vector r corresponds to w = -r.  Integrality fails only if some cone of the
prevariety meets {r : some r_i > 0}; for every such cone we test, at an interior point, that the initial system
has no torus zero over F_p (Singular: saturation by the product of the variables is the unit ideal).
If all tests pass, every common zero of G over every such valued field has v(xi_i) >= 0 for all i.

Usage (module): run(polys, gens, p, workdir, tag) -> dict with the verdict and the list of cones tested.
"""
import itertools
import json
import os
import re
import subprocess

import sympy as sp


LETTERS = 'abcdefghijklmnopqrstuvwxyz'


def to_gfan(polys, gens, path):
    """gfan's parser is not safe for names that are prefixes of other names (X2 / X23 is read as X2*3): rename the
    variables to single letters (prefix-free) before writing."""
    assert len(gens) <= len(LETTERS)
    ren = {g: sp.Symbol(LETTERS[i]) for i, g in enumerate(gens)}
    lines = []
    for f in polys:
        lines.append(str(sp.expand(sp.sympify(f).subs(ren, simultaneous=True))).replace('**', '^'))
    with open(path, 'w') as fo:
        fo.write('Q[' + ','.join(LETTERS[i] for i in range(len(gens))) + ']\n{' + ',\n'.join(lines) + '}\n')


def parse_fan(path):
    txt = open(path).read()

    lines_all = txt.split('\n')

    def section(name):
        out, on = [], False
        for line in lines_all:
            if line.strip() == name:
                on = True
                continue
            if on:
                if re.fullmatch(r'[A-Z_]+', line.strip()):
                    break
                out.append(line)
        return [l for l in out if l.strip()]
    rays = []
    for line in section('RAYS'):
        line = line.split('#')[0].strip()
        if line:
            rays.append([int(x) for x in line.split()])
    cones = []
    for line in section('CONES'):
        line = line.split('#')[0].strip()
        if line.startswith('{'):
            body = line.strip('{}').strip()
            cones.append([int(x) for x in body.split()] if body else [])
    lin = []
    for line in section('LINEALITY_SPACE'):
        line = line.split('#')[0].strip()
        if line:
            lin.append([int(x) for x in line.split()])
    return rays, cones, lin


def initial_form(f, gens, r):
    P = sp.Poly(sp.expand(f), *gens)
    terms = P.terms()
    wts = [sum(ri * ei for ri, ei in zip(r, mon)) for mon, _ in terms]
    mx = max(wts)
    return sum(int(c) * sp.prod([g ** e for g, e in zip(gens, mon)]) for (mon, c), wt in zip(terms, wts) if wt == mx)


def singular_torus_empty(polys, gens, p, path):
    """True iff the ideal generated by polys has no zero in the torus over the algebraic closure of F_p."""
    s = 'ring r = %d,(%s),dp;\noption(redSB);\n' % (p, ','.join(str(g) for g in gens))
    s += 'ideal I = ' + ',\n'.join(str(sp.expand(f)).replace('**', '^') for f in polys) + ';\n'
    s += 'poly t = ' + '*'.join(str(g) for g in gens) + ';\n'
    s += 'LIB "elim.lib";\nideal S = sat(I, t);\nideal G = std(S);\n'
    s += 'print("RESULT " + string(G[1] == 1));\nquit;\n'
    with open(path, 'w') as fo:
        fo.write(s)
    out = subprocess.run(['Singular', '-q', path], capture_output=True, text=True, timeout=3600).stdout
    m = re.search(r'RESULT (\d)', out)
    if not m:
        raise RuntimeError('Singular failed: ' + out[-500:])
    return m.group(1) == '1'


def _check_job(args):
    polys, gens, p, path, r = args
    ini = [initial_form(f, gens, r) for f in polys]
    return singular_torus_empty(ini, gens, p, path)


def run(polys, gens, p, workdir, tag, extra_gfan_args=()):
    os.makedirs(workdir, exist_ok=True)
    # coefficient check: every coefficient is a unit mod p
    for f in polys:
        for c in sp.Poly(sp.expand(f), *gens).coeffs():
            assert int(c) % p != 0, ('coefficient divisible by p', c)
    gin = os.path.join(workdir, tag + '.gfan')
    gout = os.path.join(workdir, tag + '.fan')
    to_gfan(polys, gens, gin)
    with open(gin) as fi, open(gout, 'w') as fo:
        subprocess.run(['gfan_tropicalintersection'] + list(extra_gfan_args), stdin=fi, stdout=fo,
                       stderr=subprocess.DEVNULL, check=True)
    rays, cones, lin = parse_fan(gout)
    results = []
    allok = True
    jobs = []
    # the lineality space (if any) is spanned by lin; it must not contain vectors with positive entries in a
    # nontrivial way -- handle by testing the cone {0} + lineality as well
    if lin:
        cones = [c for c in cones] + [[]]
    for ci, cone in enumerate(cones):
        if not cone and not lin:
            continue
        rs = [rays[i] for i in cone]
        pos = any(x > 0 for rr in rs for x in rr) or any(any(x != 0 for x in l) for l in lin)
        if not pos:
            continue
        r = [sum(col) for col in zip(*rs)] if rs else [0] * len(gens)
        jobs.append((ci, cone, r))
    from multiprocessing import Pool
    with Pool(int(os.environ.get('TROP_NPROC', '32'))) as pool:
        outs = pool.map(_check_job, [(polys, gens, p, os.path.join(workdir, '%s_c%d.sing' % (tag, ci)), r)
                                     for (ci, cone, r) in jobs])
    for (ci, cone, r), empty in zip(jobs, outs):
        results.append({'cone': cone, 'point': r, 'torus_empty': empty})
        if not empty:
            allok = False
    return {'tag': tag, 'n_rays': len(rays), 'n_cones': len(cones), 'tested': len(results),
            'all_empty': allok, 'failures': [x for x in results if not x['torus_empty']], 'lineality': lin}
