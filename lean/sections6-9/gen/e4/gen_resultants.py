"""Generate Lean6/Special/K4/E4/Resultants.lean: the computations of the proof of Lemma 7.7 for G_sigma.

For the tournaments T1, T2, T3 of the paper (sigma_kl = 1 for k < l, except sigma_24 = -1 in T2 and sigma_14 = -1
in T3) and xi = (0, 1, t, s): e_k = sum_{l != k} sigma_kl prod_{j != k,l} (xi_k - xi_j)^2 (k = 1, 2, 3),
R1 = Res_s(e1, e2), R2 = Res_s(e1, e3) = t^4 R2', and Res_t(R1, R2').  Computed with SymPy (exact); the generator
asserts the values printed in the paper.  Output: Bezout cofactors (A e1 + B e2 = R1, A2 e1 + B2 e3 = R2,
U R1 + V R2' = c), and an LU factorization over Q (no pivoting) of the 16 x 16 Sylvester matrix of (R1, R2') in
Mathlib's layout.  Run: python3 -I gen_resultants.py OUT.lean
"""
