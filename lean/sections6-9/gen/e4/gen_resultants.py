import sympy as sp

t, s = sp.symbols('t s')
xi = [sp.Integer(0), sp.Integer(1), t, s]
TOUR = {'T1': {}, 'T2': {(1, 3): -1}, 'T3': {(0, 3): -1}}
PRINTED = {
    'T1': (5*t**8 - 20*t**7 + 26*t**6 - 20*t**5 + 19*t**4 - 4*t**3 + 2*t**2 + 1,
           t**8 + 14*t**6 - 28*t**5 + 47*t**4 - 52*t**3 + 42*t**2 - 20*t + 5, 2**16 * 3**4 * 5**4 * 7**2 * 3881),
    'T2': (5*t**8 - 20*t**7 + 30*t**6 - 36*t**5 + 43*t**4 - 28*t**3 + 22*t**2 - 8*t + 1,
           t**8 + 14*t**6 - 28*t**5 + 47*t**4 - 52*t**3 + 42*t**2 - 20*t + 5, 2**16 * 3**8 * 5**10),
    'T3': (-3*t**8 + 12*t**7 - 18*t**6 + 20*t**5 - 17*t**4 + 4*t**3 + 2*t**2 + 1,
           t**8 - 10*t**6 + 28*t**5 - 37*t**4 + 36*t**3 - 26*t**2 + 12*t - 3, -2**16 * 5**4 * 23 * 433)}


def ek(mods):
    sg = lambda a, b: mods.get((a, b), 1) if a < b else -mods.get((b, a), 1)
    out = []
    for k in range(3):
        tot = 0
        for l in range(4):
            if l == k:
                continue
            pr = 1
            for j in range(4):
                if j != k and j != l:
                    pr *= (xi[k] - xi[j])**2
            tot += sg(k, l) * pr
        out.append(sp.expand(tot))
    return out


def bezout(f, g):
    a0, a1, b0, b1 = sp.symbols('a0 a1 b0 b1')
    R = sp.expand(sp.resultant(f, g, s))
    expr = sp.expand((a0 + a1*s)*f + (b0 + b1*s)*g - R)
    eqs = [sp.Poly(expr, s).coeff_monomial(s**i) for i in range(4)]
    sol = sp.solve(eqs, [a0, a1, b0, b1], dict=True)[0]
    A = sp.expand(sol[a0] + sol[a1]*s)
    B = sp.expand(sol[b0] + sol[b1]*s)
    assert sp.expand(A*f + B*g - R) == 0
    for c in sp.Poly(A, s, t).coeffs() + sp.Poly(B, s, t).coeffs():
        assert c.is_integer
    return A, B, R


def lean(expr):
    return str(sp.expand(expr)).replace('**', '^')


def coeffs_s(e):
    P = sp.Poly(e, s)
    return [sp.expand(P.coeff_monomial(s**i)) for i in range(3)]


def lean_tpoly(e):
    """an element of Z[t] as a Lean term of ℤ[X] (X = t)"""
    P = sp.Poly(e, t)
    terms = []
    for (k,), c in sorted(P.terms(), reverse=True):
        mon = '1' if k == 0 else ('X' if k == 1 else f'X ^ {k}')
        terms.append(f'C ({c}) * {mon}')
    return ' + '.join(terms) if terms else '0'


def sylv(f, g, m, n):
    N = m + n
    M = [[0] * N for _ in range(N)]
    for i in range(N):
        for j in range(N):
            if j < m:
                if j <= i <= j + n:
                    M[i][j] = g[i - j] if i - j < len(g) else 0
            else:
                j1 = j - m
                if j1 <= i <= j1 + m:
                    M[i][j] = f[i - j1] if i - j1 < len(f) else 0
    return M


def lu(M):
    N = len(M)
    U = [[Fr(x) for x in row] for row in M]
    L = [[Fr(int(i == j)) for j in range(N)] for i in range(N)]
    for k in range(N):
        assert U[k][k] != 0, 'zero pivot'
        for i in range(k + 1, N):
            f = U[i][k] / U[k][k]
            L[i][k] = f
            for j in range(k, N):
                U[i][j] -= f * U[k][j]
    return L, U


def qlit(x):
    return f'{x.numerator}' if x.denominator == 1 else f'({x.numerator} / {x.denominator})'


def mat_lit(M):
    return '[' + ',\n    '.join('[' + ', '.join(qlit(x) for x in row) + ']' for row in M) + ']'


