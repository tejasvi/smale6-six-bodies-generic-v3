#!/usr/bin/env python3
"""Generator of the Lean data of the checks of Lemma 6.19(c), (d) and of the last paragraph of Sec. 6.7.

Usage: python3 -I gen.py D88_CERT_DIR LEAN_ROOT [CHUNK]
  D88_CERT_DIR: the certificate directory of diagrams 88/94 (k4_cert_1_2_3_30.jsonl, kc/kc_cert_1_2_3_30.jsonl,
                count/full_1_2_3_30_p65521.ms)
  LEAN_ROOT:    the project root (writes Lean6/Special/Comp/D88/Boxes/{Sys.lean, N4/*.lean, KC/*.lean})
Needs sympy (for KC12). Deterministic.

* Sys.lean: the systems as lists of terms (`TPoly`): S11 from the msolve input of S12 (the equations of that file,
  in its variable order X2, X3, Y1, Y2, Y3, p12, ..., p34, without the Y-equation of body 3), and KC12 written here
  from the definitions (variables X2, X3, Y1, Y2, Y3, Y4, p12, ..., p34; X1 = 1, X4 = 0; masses 1, 2, 3, 30).
* N4/D<j>.lean, KC/D<j>.lean: the boxes, CHUNK per module, each as the string "r|re,im|re,im|..." with the radius
  field "r" and the midpoint field "mid" of the certificate line copied verbatim; the run theorem of the chunk.
* N4/All.lean, KC/All.lean: the list of all boxes and the theorem that every box passes.
"""
import json
import os
import re
import sys

import sympy as sp

CERT, ROOT = sys.argv[1], sys.argv[2]
CHUNK = int(sys.argv[3]) if len(sys.argv) > 3 else 64
OUT = os.path.join(ROOT, 'Lean6', 'Special', 'Comp', 'D88', 'Boxes')


def term_lean(c, mono):
    m = ', '.join(f'({v}, {e})' for v, e in mono)
    return f'⟨{c}, 0, [{m}]⟩'


def parse_ms(path):
    lines = open(path).read().split('\n')
    names = lines[0].strip().split(',')
    body = ''.join(lines[2:]).replace(' ', '')
    polys = [p for p in body.split(',') if p]
    out = []
    for p in polys:
        toks = re.findall(r'[+-]?[^+-]+', p)
        terms = []
        for t in toks:
            sg = -1 if t[0] == '-' else 1
            t = t.lstrip('+-')
            c = sg
            mono = {}
            for f in t.split('*'):
                if re.fullmatch(r'\d+', f):
                    c *= int(f)
                else:
                    m = re.fullmatch(r'([A-Za-z]\w*)(\^(\d+))?', f)
                    assert m, f
                    v = names.index(m.group(1))
                    mono[v] = mono.get(v, 0) + int(m.group(3) or 1)
            terms.append((c, sorted(mono.items())))
        out.append(terms)
    return names, out


def kc12():
    mu = [1, 2, 3, 30]
    X2, X3, Y1, Y2, Y3, Y4 = sp.symbols('X2 X3 Y1 Y2 Y3 Y4')
    ps = sp.symbols('p12 p13 p14 p23 p24 p34')
    pairs = [(0, 1), (0, 2), (0, 3), (1, 2), (1, 3), (2, 3)]
    P = dict(zip(pairs, ps))
    gens = [X2, X3, Y1, Y2, Y3, Y4] + list(ps)

    def p(a, b):
        return P[(min(a, b), max(a, b))]
    X = [sp.Integer(1), X2, X3, sp.Integer(0)]
    Y = [Y1, Y2, Y3, Y4]

    def ceq(Z, k, lhs=True):
        return (Z[k] if lhs else 0) - sum(mu[l] * p(k, l) ** 3 * (Z[k] - Z[l]) for l in range(4) if l != k)
    eqs = [ceq(X, 0), ceq(X, 1), ceq(X, 2), ceq(X, 3, lhs=False), ceq(Y, 0), ceq(Y, 1)]
    eqs += [p(a, b) ** 2 * (X[a] - X[b]) * (Y[a] - Y[b]) - 1 for (a, b) in pairs]
    out = []
    for e in eqs:
        Pp = sp.Poly(sp.expand(e), *gens)
        terms = []
        for mon, c in zip(Pp.monoms(), Pp.coeffs()):
            assert c == int(c)
            terms.append((int(c), [(i, k) for i, k in enumerate(mon) if k]))
        out.append(terms)
    return out


def write_sys():
    names, s12 = parse_ms(os.path.join(CERT, 'count', 'full_1_2_3_30_p65521.ms'))
    assert names == ['X2', 'X3', 'Y1', 'Y2', 'Y3', 'p12', 'p13', 'p14', 'p23', 'p24', 'p34'], names
    assert len(s12) == 12
    s11 = s12[:5] + s12[6:]
    kc = kc12()
    with open(os.path.join(OUT, 'Sys.lean'), 'w') as f:
        f.write('import Lean6.Special.Comp.Ball.TPoly\n\n')
        f.write('/-!\n# The systems S11 and KC12 at μ0 = (1, 2, 3, 30) as lists of terms (generated by `gen/d88boxes/gen.py`)\n\n')
        f.write('`s11T`: the equations of the msolve input of S12 (variables `X2, X3, Y1, Y2, Y3, p12, p13, p14, p23, p24, p34`\n')
        f.write('= `0, …, 10`) without the Y-equation of body 3, in the order of that file: the X-equations of bodies 1, 2, 3, the\n')
        f.write('Y-equations of bodies 1, 2, the distance equations of `12, 13, 14, 23, 24, 34` (those of `14, 24, 34` multiplied by\n')
        f.write('`μ4² = 900` to clear denominators). `kc12T`: the X-equations of bodies 1, 2, 3, 4, the Y-equations of bodies 1, 2,\n')
        f.write('the six distance equations, in the variables `X2, X3, Y1, Y2, Y3, Y4, p12, …, p34` = `0, …, 11`. Every term has\n')
        f.write('coefficient index `0` (the table `[1]`). `D88/Boxes/Systems.lean` proves that these are the equations of the paper.\n-/\n\n')
        f.write('namespace Lean6.Special.D88.Boxes\n\nopen Lean6.Special.Kraw\n\n')
        for nm, sysl in (('s11T', s11), ('kc12T', kc)):
            f.write(f'/-- The system `{nm}` (see the module docstring). -/\ndef {nm} : List TPoly := [\n')
            f.write(',\n'.join('  [' + ', '.join(term_lean(c, m) for c, m in eq) + ']' for eq in sysl))
            f.write(']\n\n')
        f.write('end Lean6.Special.D88.Boxes\n')


def raw_fields(line):
    m = re.search(r'"r": ([^,}]+)', line)
    r = m.group(1).strip()
    rec = json.loads(line)
    assert repr(rec['r']) == r or float(r) == rec['r']
    return r, rec['mid']


def write_data(kind, path, nvar):
    d = os.path.join(OUT, kind)
    os.makedirs(d, exist_ok=True)
    boxes = []
    for line in open(path):
        if not line.strip():
            continue
        r, mid = raw_fields(line)
        assert len(mid) == nvar
        s = r + '|' + '|'.join(a + ',' + b for a, b in mid)
        assert '"' not in s and '\\' not in s
        boxes.append(s)
    nch = (len(boxes) + CHUNK - 1) // CHUNK
    chk = 'n4ChunkOK' if kind == 'N4' else 'kcChunkOK'
    src = os.path.basename(path)
    for j in range(nch):
        part = boxes[j * CHUNK:(j + 1) * CHUNK]
        with open(os.path.join(d, f'D{j:03d}.lean'), 'w') as f:
            f.write('import Lean6.Special.Comp.D88.Boxes.Check\n\n')
            f.write(f'/-! Boxes {j * CHUNK}–{j * CHUNK + len(part) - 1} of `{src}` (generated by `gen/d88boxes/gen.py`). -/\n\n')
            f.write(f'namespace Lean6.Special.D88.Boxes.{kind}.D{j:03d}\n\n')
            f.write('/-- The boxes: the fields `r` and `mid` of the certificate lines, verbatim. -/\n')
            f.write('def data : List String := [\n')
            f.write(',\n'.join(f'  "{s}"' for s in part))
            f.write(']\n\n')
            f.write(f'theorem ok : {chk} data = true := by native_decide\n\n')
            f.write(f'end Lean6.Special.D88.Boxes.{kind}.D{j:03d}\n')
    with open(os.path.join(d, 'All.lean'), 'w') as f:
        for j in range(nch):
            f.write(f'import Lean6.Special.Comp.D88.Boxes.{kind}.D{j:03d}\n')
        f.write(f'\n/-! All {len(boxes)} boxes of `{src}` (generated by `gen/d88boxes/gen.py`). -/\n\n')
        f.write(f'namespace Lean6.Special.D88.Boxes.{kind}\n\n')
        f.write('/-- The chunks, in the order of the certificate file. -/\ndef allChunks : List (List String) := [\n  ')
        f.write(',\n  '.join(f'D{j:03d}.data' for j in range(nch)))
        f.write(']\n\n')
        f.write('/-- All boxes, in the order of the certificate file. -/\ndef allData : List String := allChunks.flatten\n\n')
        f.write(f'theorem allData_length : allData.length = {len(boxes)} := by native_decide\n\n')
        f.write('set_option maxRecDepth 100000 in\n')
        f.write(f'/-- Every chunk passes (from the run theorems of the chunks). -/\ntheorem chunks_ok : allChunks.all {chk} = true := by\n')
        f.write('  simp only [allChunks, List.all_cons, List.all_nil, Bool.and_true, Bool.true_and,\n    ')
        f.write(',\n    '.join(f'D{j:03d}.ok' for j in range(nch)))
        f.write(']\n\n')
        f.write(f'/-- Every box passes. -/\ntheorem all_ok : {chk} allData = true := by\n')
        f.write(f'  unfold {chk} allData\n  rw [List.all_flatten]\n  exact chunks_ok\n\n')
        f.write(f'end Lean6.Special.D88.Boxes.{kind}\n')
    print(kind, len(boxes), 'boxes', nch, 'modules')


os.makedirs(OUT, exist_ok=True)
write_sys()
write_data('N4', os.path.join(CERT, 'k4_cert_1_2_3_30.jsonl'), 11)
write_data('KC', os.path.join(CERT, 'kc', 'kc_cert_1_2_3_30.jsonl'), 12)
