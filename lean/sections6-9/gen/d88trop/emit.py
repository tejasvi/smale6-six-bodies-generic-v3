#!/usr/bin/env python3
"""Write the Lean data modules of Lemma 6.19(a) from the outputs of mkdata.py and dfs.py.
Usage: emit.py n4|kc OUTDIR LEANROOT   (LEANROOT = the directory that contains Lean6/)"""
import json
import os
import sys

import sympy as sp

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

CHUNK = 900_000
NAME = {'n4': 'N4', 'kc': 'KC'}


def mono_tokens(e):
    nz = [(i, k) for i, k in enumerate(e) if k]
    return [len(nz)] + [t for ik in nz for t in ik]


def poly_tokens_int(terms):
    out = [len(terms)]
    for c, e in terms:
        out += [c] + mono_tokens(e)
    return out


def sym_poly_terms(expr, gens):
    P = sp.Poly(sp.expand(sp.sympify(expr)), *gens) if sp.sympify(expr) != 0 else None
    if P is None or P.is_zero:
        return []
    return [(int(c), tuple(e)) for e, c in P.terms()]


def lean_string(s):
    assert '"' not in s and '\\' not in s
    return '"' + s + '"'


def module(path, ns, defs, doc, extra_nat=()):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    lines = ['/-! ' + doc + ' -/', '', 'namespace ' + ns, '']
    for name, val, d in defs:
        lines.append('/-- ' + d + ' -/')
        lines.append('def %s : String :=' % name)
        lines.append('  ' + lean_string(val))
        lines.append('')
    for name, val, d in extra_nat:
        lines.append('/-- ' + d + ' -/')
        lines.append('def %s : Nat := %d' % (name, val))
        lines.append('')
    lines.append('end ' + ns)
    open(path, 'w').write('\n'.join(lines) + '\n')


def main():
    kind, outdir, root = sys.argv[1], sys.argv[2], sys.argv[3]
    N = NAME[kind]
    D = json.load(open(os.path.join(outdir, '%s_data.json' % kind)))
    G = D['G']
    gt = [len(G)]
    for g in G:
        gt.append(len(g))
        for e, cp in g:
            gt += mono_tokens(e)
            gt += poly_tokens_int([(c, me) for c, me in cp])
    mu = sp.symbols('mu1 mu2 mu3 mu4')
    vs = sp.symbols(' '.join(D['v']))
    iu = sp.Symbol('iu')
    gens = list(vs) + list(mu) + [iu]
    ct = [len(D['cof'])]
    for cofs in D['cof']:
        assert len(cofs) == 13
        for c in cofs:
            ct += poly_tokens_int(sym_poly_terms(c, gens))
    ft = [len(D['gfan'])]
    for g in D['gfan']:
        ft += poly_tokens_int([(c, e) for e, c in g])
    st = ' '.join(str(x) for x in D['scal'])
    hp = os.path.join(outdir, '%s_hyps.json' % kind)
    hyps = json.load(open(hp)) if os.path.exists(hp) else []
    ht = [len(hyps)]
    for h in hyps:
        ht.append(len(h))
        for f in h:
            ht += poly_tokens_int([(c, e) for c, e in f])
    base = os.path.join(root, 'Lean6/Special/Comp/D88/Trop')
    ns = 'Lean6.Special.Comp.D88.Trop.Data' + N
    module(os.path.join(base, 'Data%s.lean' % N), ns,
           [('gStr', ' '.join(map(str, gt)), 'The polynomials of `G` (`%s`), grouped by `ξ`-monomials.' % N),
            ('cofStr', ' '.join(map(str, ct)), 'The cofactors `c₁, …, c₁₂, c₀` of the identities (i).'),
            ('gfanStr', ' '.join(map(str, ft)), 'The gfan input of the d88 run (`ξ` = the letters `a, …, q`).'),
            ('scalStr', st, 'The unit scalars `s` with `Gbar = s · gfan` modulo `p`.'),
            ('hypStr', ' '.join(map(str, ht)), 'The systems whose torus emptiness is assumed (leaves `hyp` of the covering).')],
           'Generated by `gen/d88trop/emit.py` from `mkdata.py` and `dfs.py` (do not edit). Data of Lemma 6.19(a), system %s.' % N,
           [('hypCount', len(hyps), 'The number of assumed systems.')])
    tree = open(os.path.join(outdir, '%s_tree.txt' % kind)).read().split()
    chunks, cur, size = [], [], 0
    for t in tree:
        cur.append(t)
        size += len(t) + 1
        if size >= CHUNK:
            chunks.append(' '.join(cur))
            cur, size = [], 0
    if cur:
        chunks.append(' '.join(cur))
    tdir = os.path.join(base, 'Tree%s' % N)
    os.makedirs(tdir, exist_ok=True)
    for f in os.listdir(tdir):
        if f.startswith('T') and f.endswith('.lean'):
            os.remove(os.path.join(tdir, f))
    names = []
    for k, ch in enumerate(chunks):
        nm = 'T%03d' % k
        names.append(nm)
        module(os.path.join(tdir, nm + '.lean'), 'Lean6.Special.Comp.D88.Trop.Tree%s.%s' % (N, nm),
               [('s', ch, 'Chunk %d of the covering tree.' % k)],
               'Generated by `gen/d88trop/emit.py` from `dfs.py` (do not edit). Covering tree of Lemma 6.19(a), system %s, chunk %d.' % (N, k))
    agg = ['import Lean6.Special.Comp.D88.Trop.Tree%s.%s' % (N, nm) for nm in names]
    agg += ['', '/-! Generated by `gen/d88trop/emit.py` (do not edit): the covering tree of system %s, %d tokens. -/' % (N, len(tree)), '',
            'namespace Lean6.Special.Comp.D88.Trop', '',
            '/-- The covering tree of `%s` (prefix order, tokens separated by spaces). -/' % N,
            'def tree%s : String :=' % N,
            '  String.intercalate " " [' + ', '.join('Tree%s.%s.s' % (N, nm) for nm in names) + ']', '',
            'end Lean6.Special.Comp.D88.Trop']
    open(os.path.join(base, 'Tree%s.lean' % N), 'w').write('\n'.join(agg) + '\n')
    print(kind, 'G tokens', len(gt), 'cof tokens', len(ct), 'tree tokens', len(tree), 'chunks', len(chunks))


if __name__ == '__main__':
    main()
