#!/usr/bin/env python3
"""Write the run modules of the C_4 chart checks: one module per (masses, prime, chart) with one `native_decide`
theorem, and one module per (masses, prime) collecting the fourteen charts. Usage: python3 gen_runs.py ROOT
(ROOT = the project directory). Deterministic."""
import os
import sys

root = sys.argv[1]
CONFIGS = [('M0P32003', 'mu0', 32003), ('M0P1073741789', 'mu0', 1073741789),
           ('M1P32003', 'mu1', 32003), ('M1P1073741789', 'mu1', 1073741789)]
NAMES = ['s', 't', 'p12', 'p13', 'p14', 'p23', 'p24', 'p34', 'c']
CHARTS = [(a, b) for a in (0, 1) for b in (2, 3, 4, 5, 6, 7, 8)]
base = os.path.join(root, 'Lean6', 'Special', 'Comp', 'K4', 'C4', 'Run')
for tag, mu, p in CONFIGS:
    d = os.path.join(base, tag)
    os.makedirs(d, exist_ok=True)
    mods = []
    for (a, b) in CHARTS:
        nm = '%s_%s' % (NAMES[a].upper(), NAMES[b].upper())
        mods.append(nm)
        with open(os.path.join(d, nm + '.lean'), 'w') as f:
            f.write('import Lean6.Special.Comp.K4.C4.Check\n\n')
            f.write('/-! Generated by `gen/c4/gen_runs.py`: the chart %s = 1, %s = 1, masses `%s`, prime %d. -/\n\n'
                    % (NAMES[a], NAMES[b], mu, p))
            f.write('namespace Lean6.Special.Comp.C4.Run.%s.%s\n\n' % (tag, nm))
            f.write('theorem ok : chartOK %s %d (%d, %d) = true := by native_decide\n\n' % (mu, p, a, b))
            f.write('end Lean6.Special.Comp.C4.Run.%s.%s\n' % (tag, nm))
    with open(os.path.join(base, tag + '.lean'), 'w') as f:
        for nm in mods:
            f.write('import Lean6.Special.Comp.K4.C4.Run.%s.%s\n' % (tag, nm))
        f.write('\n/-! Generated by `gen/c4/gen_runs.py`: the fourteen charts, masses `%s`, prime %d. -/\n\n' % (mu, p))
        f.write('namespace Lean6.Special.Comp.C4.Run.%s\n\n' % tag)
        f.write('theorem all : ∀ ch ∈ charts, chartOK %s %d ch = true := by\n' % (mu, p))
        f.write('  intro ch hch\n')
        f.write('  rw [charts_eq] at hch\n')
        f.write('  simp only [List.mem_cons, List.mem_nil_iff, or_false] at hch\n')
        f.write('  rcases hch with ' + ' | '.join(['rfl'] * len(mods)) + '\n')
        for nm in mods:
            f.write('  · exact %s.ok\n' % nm)
        f.write('\n')
        f.write('end Lean6.Special.Comp.C4.Run.%s\n' % tag)
print('ok')
