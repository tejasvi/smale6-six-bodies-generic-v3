#!/usr/bin/env python3
"""Generate Lean6/Special/Comp/D88/Count/Sys.lean: the msolve inputs of Lemma 6.19(b) as integer term lists.
Usage: br_mkinputs.py S12.ms KCPRIME.ms OUT.lean
The .ms files are msolve inputs: line 1 the variables, line 2 the characteristic, then the polynomials separated by
commas, each a sum of terms 'c*x^e*...' with integer coefficients."""
import re
import sys


def parse_ms(path):
    lines = open(path).read().split('\n')
    names = lines[0].strip().split(',')
    body = ''.join(lines[2:]).strip()
    polys = [q.strip() for q in body.split(',') if q.strip()]
    out = []
    for q in polys:
        toks = re.findall(r'[+-]?[^+-]+', q.replace(' ', ''))
        terms = {}
        for t in toks:
            sg = -1 if t[0] == '-' else 1
            t = t.lstrip('+-')
            c = 1
            e = [0] * len(names)
            for f in t.split('*'):
                if re.fullmatch(r'\d+', f):
                    c *= int(f)
                else:
                    m = re.fullmatch(r'([A-Za-z]\w*)(\^(\d+))?', f)
                    assert m, (f, q[:60])
                    e[names.index(m.group(1))] += int(m.group(3) or 1)
            k = tuple(e)
            terms[k] = terms.get(k, 0) + sg * c
        out.append([(c, list(k)) for k, c in terms.items() if c != 0])
    return names, out


def lean_poly(p):
    return '[' + ', '.join('(%d, [%s])' % (c, ', '.join(map(str, e))) for c, e in p) + ']'


def main():
    s12_names, s12 = parse_ms(sys.argv[1])
    kc_names, kc = parse_ms(sys.argv[2])
    assert s12_names == ['X2', 'X3', 'Y1', 'Y2', 'Y3', 'p12', 'p13', 'p14', 'p23', 'p24', 'p34'], s12_names
    assert kc_names == ['X2', 'X3', 'U1', 'U2', 'U3', 'p12', 'p13', 'p14', 'p23', 'p24', 'p34'], kc_names
    assert len(s12) == 12 and len(kc) == 12
    out = ['import Lean6.Special.Comp.Poly', '',
           '/-! Generated by `gen/d88count/br_mkinputs.py` from the msolve inputs of Lemma 6.19(b) (sha256 in',
           '`data/d88count/SHA256SUMS_br`): the systems S12 (unknowns X2, X3, Y1, Y2, Y3, p12, …, p34) and KC′ (unknowns',
           'X2, X3, U1, U2, U3, p12, …, p34) at μ₀ = (1, 2, 3, 30), as integer term lists, and their reductions modulo',
           '`65521`, the inputs of the engines. -/', '',
           'namespace Lean6.Special.Comp.Count', '', 'open Lean6.Special.Comp', '',
           '/-- The polynomials of S12 (the msolve input), integer coefficients. -/',
           'def s12InputsZ : List (Poly Int) := [']
    out.append(',\n'.join('  ' + lean_poly(p) for p in s12) + ']')
    out += ['', '/-- The polynomials of KC′ (the msolve input), integer coefficients. -/',
            'def kcInputsZ : List (Poly Int) := [']
    out.append(',\n'.join('  ' + lean_poly(p) for p in kc) + ']')
    out += ['', '/-- Reduction of the coefficients modulo `p`. -/',
            'def reduceMod (p : Nat) (f : Poly Int) : Poly Nat := f.map fun t => ((t.1 % (p : Int)).toNat, t.2)', '',
            '/-- The engine input for S12. -/', 'def s12Inputs : List (Poly Nat) := s12InputsZ.map (reduceMod 65521)', '',
            '/-- The engine input for KC′. -/', 'def kcInputs : List (Poly Nat) := kcInputsZ.map (reduceMod 65521)', '',
            'end Lean6.Special.Comp.Count', '']
    open(sys.argv[3], 'w').write('\n'.join(out))
    print('S12 terms', sum(len(p) for p in s12), 'KC terms', sum(len(p) for p in kc))


if __name__ == '__main__':
    main()
