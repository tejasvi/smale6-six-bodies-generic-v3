#!/usr/bin/env python3
"""Writes L6Check/F34/All.lean: the arguments of the 123 chunk theorems `F34_c<N>_k<k>` as one list `chunkArgs`
(read verbatim from the statements of L6Check/F34/C<N>K<k>.lean), the theorem `F34_all` that every entry passes
(each case is the chunk theorem), and the totals and the coverage of the classes computed from the same list, so
that the counts are formally those of the checked chunks. Run from the package root (untrusted: Lean checks it)."""
import os, re
D = 'L6Check/F34'
files = sorted((f for f in os.listdir(D) if re.fullmatch(r'C\d+K\d+\.lean', f)),
               key=lambda f: tuple(int(x) for x in re.findall(r'\d+', f)))
entries, thms = [], []
for f in files:
    t = open(os.path.join(D, f)).read()
    m = re.search(r'theorem (F34_c(\d+)_k(\d+)) : checkChunk (\d+) n6 (cells_\d+) (single_\d+) (links_\d+) (pass_\d+) open43\s*'
                  r'(\[.*?\])\s*(\d+) (\d+) (\{[^}]*\}) = true', t, re.S)
    assert m, f
    name, cls, k, cls2, cells, single, links, pas, certs, lo, hi, cnt = m.groups()
    assert cls == cls2
    entries.append(f'  ⟨{cls}, {cells}, {single}, {links}, {pas},\n    {certs},\n    {lo}, {hi}, {cnt}⟩')
    thms.append(name)
n = len(entries)
cov = open(os.path.join(D, 'Cover.lean')).read()
mm = re.search(r'theorem F34_cover : \[[^\]]*\] =\s*(\[[\d,\s]*\])', cov)
assert mm
ncells = mm.group(1)
imports = '\n'.join(f'import L6Check.F34.{f[:-5]}' for f in files)
pat = ' | '.join(['rfl'] * n)
cases = '\n'.join(f'  · exact {t}' for t in thms)
txt = f'''-- Generated by scripts/f34/gen_all.py; do not edit.
{imports}
import L6Check.F34.Cover

/-! F3/F4 (Proposition 5.3), all chunks at once: the arguments of the {n} chunk theorems as one list, the theorem
that every entry passes, and the totals and coverage computed from that list. -/

namespace L6.F34.Checks

open L6.F34 L6.F34.Data

/-- The arguments of a chunk check. -/
structure ChunkArgs where
  cls : Nat
  cells : String
  single : String
  links : String
  pass : String
  certs : List (String × String)
  lo : Nat
  hi : Nat
  expected : Counts

/-- The check of a chunk. -/
def ChunkArgs.ok (a : ChunkArgs) : Bool :=
  checkChunk a.cls n6 a.cells a.single a.links a.pass open43 a.certs a.lo a.hi a.expected

/-- The {n} chunks, as in the theorems `F34_c<class>_k<k>` (used only in proofs and kernel reductions). -/
noncomputable def chunkArgs : List ChunkArgs := [
{",\n".join(entries)}]

/-- **Every chunk passes** (each case is a chunk theorem). -/
theorem F34_all : ∀ a ∈ chunkArgs, a.ok = true := by
  intro a ha
  simp only [chunkArgs, List.mem_cons, List.not_mem_nil, or_false] at ha
  rcases ha with {pat}
{cases}

/-- The totals over the checked chunks: single-term cells, first-pass core cells, second-pass core cells, open
cells. -/
theorem F34_all_totals :
    (chunkArgs.map (·.expected.single)).sum = 52432 ∧ (chunkArgs.map (·.expected.core1)).sum = 37808 ∧
    (chunkArgs.map (·.expected.core2)).sum = 990 ∧ (chunkArgs.map (·.expected.opn)).sum = 43 := by
  decide +kernel

/-- The chunks of each class `c < 191` are consecutive, in the order of the list, from `0` to `ncells[c]`. -/
noncomputable def coverOKArgs (ncells : List Nat) : Bool :=
  (List.range 191).all fun c =>
    let rs := chunkArgs.filter (·.cls == c)
    (rs.foldl (fun (pos : Option Nat) r => pos.bind fun p => if r.lo == p then some r.hi else none) (some 0)) ==
      some (ncells.getD c 0)

/-- The chunks of each class cover its cells: with `F34_cover` (the numbers of lines of the embedded cell lists),
the chunks of class `c` are the cells `0 ≤ idx < numCells cells_c`, in order. -/
theorem F34_all_cover : coverOKArgs {ncells} = true := by
  decide +kernel

end L6.F34.Checks
'''
open(os.path.join(D, 'All.lean'), 'w').write(txt)
print(n, 'chunks')
