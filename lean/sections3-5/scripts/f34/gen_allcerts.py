#!/usr/bin/env python3
"""Writes, from the statements of the chunk theorems:
  L6Check/F34/CertsOK/C<N>K<k>.lean  `certsOK_c<N>_k<k>`: every certificate text named in the chunk passes `checkCert`
                                     (the cases are the theorems `L6.Poly.Checks.cert_<certid>`);
  L6Check/F34/AllCerts.lean          `F34_all_certs` (all chunks of `chunkArgs`) and `F34_all_meaning`, the meaning of
                                     all chunks by `L6.F34.chunk_meaning`.
Run from the package root after scripts/f34/gen_all.py (untrusted: Lean checks it)."""
import os, re
D = 'L6Check/F34'
os.makedirs(f'{D}/CertsOK', exist_ok=True)
files = sorted((f for f in os.listdir(D) if re.fullmatch(r'C\d+K\d+\.lean', f)),
               key=lambda f: tuple(int(x) for x in re.findall(r'\d+', f)))
names = []
for f in files:
    t = open(os.path.join(D, f)).read()
    m = re.search(r'theorem F34_c(\d+)_k(\d+) : checkChunk \d+ n6 cells_\d+ single_\d+ links_\d+ pass_\d+ open43\s*(\[.*?\])\s*\d+ \d+ \{', t, re.S)
    assert m, f
    cls, k, certs = m.groups()
    ids = re.findall(r'\("([0-9a-f]{16})", L6\.Certs\.C\1\)', certs)
    nm = f'certsOK_c{cls}_k{k}'
    names.append(nm)
    if ids:
        pat = ' | '.join(['rfl'] * len(ids))
        ex = '\n'.join(f'  · exact L6.Poly.Checks.cert_{i}' for i in ids)
        proof = (f'  intro p hp\n  simp only [List.mem_cons, List.not_mem_nil, or_false] at hp\n'
                 f'  rcases hp with {pat}\n{ex}')
    else:
        proof = '  intro p hp\n  simp at hp'
    txt = (f'-- Generated by scripts/f34/gen_allcerts.py; do not edit.\nimport L6Check.F34.{f[:-5]}\nimport L6Check.Poly.Index\n\n'
           f'namespace L6.F34.Checks\n\nset_option maxRecDepth 100000 in\nset_option maxHeartbeats 0 in\n'
           f'/-- The certificate texts of chunk `F34_c{cls}_k{k}` pass `checkCert`. -/\n'
           f'theorem {nm} : ∀ p ∈ ({certs} : List (String × String)), L6.Poly.checkCert p.2 = true := by\n{proof}\n\n'
           f'end L6.F34.Checks\n')
    p = f'{D}/CertsOK/C{cls}K{k}.lean'
    if not os.path.exists(p) or open(p).read() != txt:
        open(p, 'w').write(txt)
n = len(names)
pat_all = ' | '.join(['rfl'] * n)
cases = '\n'.join(f'  · exact {nm}' for nm in names)
imports = '\n'.join(f'import L6Check.F34.CertsOK.{f[:-5]}' for f in files)
txt = f'''-- Generated by scripts/f34/gen_allcerts.py; do not edit.
import L6Check.F34.All
{imports}
import L6Sound.Composed

/-! F3/F4 (Proposition 5.3): every certificate named in a chunk passes `checkCert`, and the meaning of all {n}
chunks, by `L6.F34.chunk_meaning` (Lemma 4.6 and the soundness of the certificates). -/

namespace L6.F34.Checks

open L6.F34 L6.F34.Data

/-- Every certificate text named in a chunk passes `checkCert`. -/
theorem F34_all_certs : ∀ a ∈ chunkArgs, ∀ p ∈ a.certs, L6.Poly.checkCert p.2 = true := by
  intro a ha
  simp only [chunkArgs, List.mem_cons, List.not_mem_nil, or_false] at ha
  rcases ha with {pat_all}
{cases}

/-- **Proposition 5.3, the computation, all chunks.** For every chunk, every cell `lo ≤ idx < hi` of the class's
stored list is one of the 43 open cells, or a single-term cell whose named term has, at every point of the strict
form of the cell polyhedron `Π`, strictly the least exponent (the hypothesis of Lemma 5.1), or a core cell with a
polynomial `h(m)`, nonzero at `hPoint F`, that vanishes wherever the initial forms of its core vanish (the hypothesis
of Lemma 5.2, without saturation). With `F34_all_cover` and `F34_cover`, the chunks of each class are all its
cells. -/
theorem F34_all_meaning : ∀ a ∈ chunkArgs,
    ∃ cd, prepare a.cls n6 a.cells a.single a.links a.pass open43 a.certs = some cd ∧
      ∀ idx, a.lo ≤ idx → idx < a.hi →
        cd.opens.contains idx = true ∨
        (∃ nm lab x c rows pt, cd.single.getD idx none = some (nm, lab) ∧ cellCtx cd idx = some (x, c, rows, pt) ∧
          ∃ ts i, x.secTerms nm = some ts ∧ findLab ts lab = some i ∧
            ∀ k, k < ts.size → k ≠ i → ∀ hgt : ℕ → ℚ, (∀ r ∈ rows, r.StrictHolds x.nh hgt) →
              ¬ (rowLe ts k i).StrictHolds x.nh hgt) ∨
        (∃ lk cert x c rows pt, cd.links.getD idx none = some lk ∧ cd.certs.lookup lk.cert = some cert ∧
          cellCtx cd idx = some (x, c, rows, pt) ∧
          (∀ {{R : Type}} [CommRing R] (φ : ℕ → R),
            (∀ i, i < lk.names.size → ∀ g, genFor x c rows pt lk lk.names[i]! = some g →
              L6.Poly.eval (6 + cert.nvar) φ g = 0) → L6.Poly.eval 6 φ cert.h = 0) ∧
          L6.Poly.eval 6 (fun i => (L6.Poly.hPoint cert.fixed).getD i (0 : ℤ)) cert.h ≠ 0) :=
  fun a ha => L6.F34.chunk_meaning (F34_all a ha) (F34_all_certs a ha)

end L6.F34.Checks
'''
open(f'{D}/AllCerts.lean', 'w').write(txt)
print(n, 'chunks')
