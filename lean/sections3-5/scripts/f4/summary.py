#!/usr/bin/env python3
"""Summary of the F4 run: counts from logs/f4/collect.json, the certificates on disk, logs/f4/lift.jsonl and the
link files; writes logs/f4/SUMMARY.md (counts point to the log files they come from).
Usage: summary.py RUN_DIR"""
import glob
import json
import os
import sys
from collections import Counter, defaultdict

RUN = sys.argv[1]


def main():
    col = json.load(open(os.path.join(RUN, 'logs', 'f4', 'collect.json')))
    cores = {}
    for ln in open(os.path.join(RUN, 'data', 'f4', 'cores.jsonl')):
        c = json.loads(ln)
        c.pop('block')
        cores[c['certid']] = c
    certs = {}
    for f in os.listdir(os.path.join(RUN, 'data', 'f4', 'certs')):
        if f.endswith('.txt') or f.endswith('.txt.gz'):
            certs[f.split('.')[0]] = (f, os.path.getsize(os.path.join(RUN, 'data', 'f4', 'certs', f)))
    attempts = defaultdict(list)
    lines = {}
    for i, ln in enumerate(open(os.path.join(RUN, 'logs', 'f4', 'lift.jsonl'))):
        r = json.loads(ln)
        r['_line'] = i + 1
        attempts[r['certid']].append(r)
    # the attempt that produced the kept file: the ok record whose size matches the file on disk
    kept = {}
    for cid, (f, size) in certs.items():
        cand = [r for r in attempts[cid] if r['status'] == 'ok' and r.get('gz_bytes', r.get('cert_bytes')) == size]
        kept[cid] = cand[-1] if cand else None
    links = []
    for f in sorted(glob.glob(os.path.join(RUN, 'data', 'f4', 'links', 'c*.txt'))):
        for ln in open(f):
            t = ln.split()
            links.append((int(t[0]), int(t[1]), t[2], int(t[3])))
    out = []
    w = out.append
    w('# F4 summary: cofactor certificates for the cores of Proposition 5.3')
    w('')
    w('Generated by `scripts/f4/summary.py` from `logs/f4/collect.json`, `logs/f4/lift.jsonl` (line numbers below),')
    w('`data/f4/cores.jsonl`, `data/f4/links/` and the files in `data/f4/certs/`.')
    w('')
    w('## Cells and cores (`logs/f4/collect.json`)')
    w('')
    w('After the replacements below; `distinct_cores_first_pass` and `distinct_cores_alt` count the distinct cores')
    w('with F = -1 and F >= 0.')
    w('')
    for k in ['first_pass_core_records', 'first_pass_cells', 'first_pass_distinct_within_classes',
              'cert_jsonl_entries_dim_minus1', 'first_pass_core_not_certified', 'first_pass_not_verified_modp',
              'first_pass_certified_but_single_term', 'alt_cells', 'duplicate_cells_across_passes',
              'uncertified_minus_alt', 'uncertified_minus_alt_equals_open43', 'scaled_2', 'link_files', 'link_lines',
              'distinct_cores', 'distinct_cores_first_pass', 'distinct_cores_alt']:
        w(f'* `{k}`: {col.get(k, 0)}')
    w('')
    ce = os.path.join(RUN, 'logs', 'f4', 'collect_engine.json')
    rep0 = os.path.join(RUN, 'logs', 'f4', 'replaced.jsonl')
    if os.path.exists(ce):
        e = json.load(open(ce))
        neng = len({json.loads(ln)['engine_certid'] for ln in open(rep0)}) if os.path.exists(rep0) else 0
        w(f'With the stored cores only (`logs/f4/collect_engine.json`, `collect.py` without `--replace`): '
          f'{e["distinct_cores"]} distinct cores')
        w(f'({e["distinct_cores_first_pass"]} first pass, {e["distinct_cores_alt"]} second pass), of which '
          f'{e["distinct_cores"] - neng} have a certificate and {neng} do not (their cells are listed below).')
        w('')
    ncore = len(cores)
    ok = [cid for cid in cores if cid in certs]
    missing = [cid for cid in cores if cid not in certs]
    w('## Certificates')
    w('')
    w(f'* distinct cores: {ncore}; with a verified certificate in `data/f4/certs/`: {len(ok)}; without: {len(missing)}.')
    for kind, lab in (('a', 'F = -1 (Lemma 5.2(a))'), ('b', 'F >= 0 (Lemma 5.2(b))')):
        n = sum(1 for c in cores.values() if c['kind'] == kind)
        m = sum(1 for cid in ok if cores[cid]['kind'] == kind)
        w(f'* cores with {lab}: {m} of {n} certified.')
    cells_ok = sum(1 for l in links if l[2] in certs)
    w(f'* link lines (cells): {len(links)}; cells whose certificate exists: {cells_ok}; without: {len(links) - cells_ok}.')
    w(f'* cells linked to a core with F = -1: {sum(1 for l in links if l[3] < 0)}; with F >= 0: '
      f'{sum(1 for l in links if l[3] >= 0)}.')
    tot = sum(s for f, s in certs.values())
    ngz = sum(1 for f, s in certs.values() if f.endswith('.gz'))
    txt_bytes = sum(kept[cid]['cert_bytes'] for cid in certs if kept.get(cid))
    w(f'* size on disk: {tot} bytes in {len(certs)} files ({ngz} gzipped); uncompressed text: {txt_bytes} bytes.')
    st = Counter(r['status'] for rs in attempts.values() for r in rs)
    w(f'* attempts in `logs/f4/lift.jsonl`: {sum(st.values())}; by status: ' +
      ', '.join(f'{k} {v}' for k, v in sorted(st.items())) + '.')
    meth = Counter((r['method'], r['order'], r['varorder']) for r in kept.values() if r)
    w('* method of the kept certificates: ' + ', '.join(f'{m}/{o}/{v} {n}' for (m, o, v), n in meth.most_common()) +
      '.')
    times = sorted((r['lift_s'], cid) for cid, r in kept.items() if r)
    if times:
        w(f'* Singular time of the kept certificates: median {times[len(times) // 2][0]} s, max {times[-1][0]} s '
          f'(`{times[-1][1]}`); total {round(sum(t for t, _ in times))} s.')
        vt = sorted((r['verify_s'], cid) for cid, r in kept.items() if r)
        w(f'* verification time (python-flint, from the written file): max {vt[-1][0]} s, total '
          f'{round(sum(t for t, _ in vt))} s.')
    w('')
    chk = os.path.join(RUN, 'logs', 'f4', 'check.json')
    if os.path.exists(chk):
        ck = json.load(open(chk))
        w('## Checks (`logs/f4/check.json`, `check.py`)')
        w('')
        w(f'* link lines checked against the engine data parsed with SymPy: {ck["link_lines_checked"]}; problems: '
          f'{len(ck["link_problems"])}.')
        w(f'* replacement cores whose (name, polynomial) pairs are not all in the cell\'s stored initial system: '
          f'{len(ck.get("replacement_pairs_not_in_system", []))}.')
        w(f'* certificates referenced: {ck["certificates_referenced"]}; verified from the files: '
          f'{ck.get("certificates_verified")}; failures: {len(ck.get("certificate_failures", []))}; files in '
          f'`data/f4/certs/`: {ck["files_in_certs"]}; unreferenced: {len(ck["unreferenced_files"])}.')
        w('')
    drops = sorted(glob.glob(os.path.join(RUN, 'logs', 'f4', 'dropone_*.jsonl')))
    if drops:
        dd = {}
        for f in drops:
            for ln in open(f):
                if ln.startswith('{'):
                    r = json.loads(ln)
                    if r['certid'] not in dd or r['irredundant'] or all(
                            x is not None for x in r['drop_dims'] + [r['full_dim']]):
                        dd[r['certid']] = r
        nirr = sum(1 for r in dd.values() if r['irredundant'])
        und = [cid for cid, r in dd.items() if not r['irredundant']]
        w('## Irredundancy of the replaced stored cores (`logs/f4/dropone_*.jsonl`, `dropone.py`)')
        w('')
        w(f'{len(dd)} stored cores tested modulo 32003 at random masses: {nirr} irredundant (the core is the unit ideal')
        w('and no core with one generator dropped is); not decided (a test exceeded its time limit): ' +
          (', '.join(f'`{c}`' for c in sorted(und)) if und else 'none') + '.')
        w('')
    w('## Largest certificates')
    w('')
    w('| certid | kind | F | V | G | cells | file | bytes on disk | text bytes | Singular s | method | log line |')
    w('|---|---|---|---|---|---|---|---|---|---|---|---|')
    for cid in sorted(certs, key=lambda c: -certs[c][1])[:15]:
        c = cores[cid]
        r = kept.get(cid) or {}
        w(f'| `{cid}` | {c["kind"]} | {c["fixed"]} | {c["nvar"]} | {c["ngens"]} | {c["cells"]} | {certs[cid][0]} | '
          f'{certs[cid][1]} | {r.get("cert_bytes")} | {r.get("lift_s")} | {r.get("method")}/{r.get("order")}/'
          f'{r.get("varorder")} | {r.get("_line")} |')
    w('')
    rep = os.path.join(RUN, 'logs', 'f4', 'replaced.jsonl')
    if os.path.exists(rep):
        rr = [json.loads(ln) for ln in open(rep)]
        w('## Cells whose stored core was replaced (`logs/f4/replaced.jsonl`)')
        w('')
        w(f'{len(rr)} cells. For these the stored core (column "engine core") has no certificate (see the attempts in')
        w('`logs/f4/lift.jsonl`); another subset of the same initial system, found by `altcore.py` and certified by')
        w('`lift.py`, is linked instead (its names list is in the link line).')
        w('')
        w('| class | cell | engine core | engine F | new core | new F | generators | file bytes |')
        w('|---|---|---|---|---|---|---|---|')
        for r in rr:
            size = certs.get(r['certid'], (None, None))[1]
            w(f'| {r["class"]} | {r["cell"]} | `{r["engine_certid"]}` | {r["engine_fixed"]} | `{r["certid"]}` | '
              f'{r["fixed"]} | {len(r["names"])} | {size} |')
        w('')
    ten = [(3, 8722), (3, 13414), (3, 17222), (3, 24695), (3, 31349), (3, 41091), (3, 41143), (3, 41569), (14, 218),
           (30, 122)]
    eng = {}
    if os.path.exists(rep):
        for r in rr:
            eng[(r['class'], r['cell'])] = r['engine_certid']
    for l in links:
        if (l[0], l[1]) in ten and (l[0], l[1]) not in eng:
            eng[(l[0], l[1])] = l[2]
    w('## The ten cores that rest on Singular alone (paper, Section 9)')
    w('')
    w('| class | cell | engine core | attempts (method/order/variables: status, Singular seconds, max RSS MB; log line) |')
    w('|---|---|---|---|')
    for k in ten:
        cid = eng.get(k)
        tried = '; '.join(f'{r["method"]}/{r["order"]}/{r["varorder"]}: {r["status"]}, {r.get("lift_s")} s, '
                          f'{r.get("lift_maxrss_mb")} MB (line {r["_line"]})' for r in attempts.get(cid, []))
        w(f'| {k[0]} | {k[1]} | `{cid}` | {tried} |')
    w('')
    w('## Cores without a certificate')
    w('')
    if not missing:
        w('None.')
    for cid in missing:
        c = cores[cid]
        tried = ', '.join(f'{r["method"]}/{r["order"]}/{r["varorder"]}: {r["status"]} {r.get("lift_s")} s '
                          f'(line {r["_line"]})' for r in attempts[cid])
        cl = [f'{l[0]}:{l[1]}' for l in links if l[2] == cid]
        w(f'* `{cid}` (kind {c["kind"]}, F {c["fixed"]}, V {c["nvar"]}, G {c["ngens"]}; cells {" ".join(cl)}): '
          f'{tried or "not attempted"}')
    w('')
    w('## Reproduce')
    w('')
    w('```')
    w('python3 scripts/f4/collect.py IN_DIR RUN_DIR')
    w('python3 scripts/f4/lift.py RUN_DIR --jobs 200 --timeout 1800 --memcap 64 --minfree 80 --tag sweep1')
    w('python3 scripts/f4/lift.py RUN_DIR --jobs 100 --timeout 1800 --method elim --tag sweep2_elim')
    w('python3 scripts/f4/lift.py RUN_DIR --jobs 100 --timeout 1800 --method liftstd_slimgb --tag sweep2_liftstd_slimgb')
    w('python3 scripts/f4/altcore.py SYSTEMS.jsonl RUN_DIR --tries 8 --seed 1')
    w('python3 scripts/f4/altcore.py SYSTEMS.jsonl RUN_DIR --tries 24 --t0 8 --bias 3 --seed 1 --out cand_cores2.jsonl')
    w('python3 scripts/f4/lift.py RUN_DIR --cores RUN_DIR/data/f4/cand_cores.jsonl --timeout 600 --method liftstd_slimgb')
    w('python3 scripts/f4/lift.py RUN_DIR --only @BIG1.txt --force --timeout 600 --method liftstd_slimgb  # files > 1 MB')
    w('python3 scripts/f4/lift.py RUN_DIR --only @BIG2.txt --force --timeout 600 --method elim            # files > 1 MB')
    w('python3 scripts/f4/lift.py RUN_DIR --only @BIG3.txt --force --timeout 600 --varorder rev           # files > 2 MB')
    w('python3 scripts/f4/lift.py RUN_DIR --only @BIG3.txt --force --timeout 600 --varorder rev --method liftstd_slimgb')
    w('python3 scripts/f4/choose.py RUN_DIR HARDCELLS.txt')
    w('python3 scripts/f4/collect.py IN_DIR RUN_DIR --replace RUN_DIR/data/f4/replacements.jsonl')
    w('python3 scripts/f4/prune.py RUN_DIR')
    w('python3 scripts/f4/check.py IN_DIR RUN_DIR --replace RUN_DIR/data/f4/replacements.jsonl --systems SYSTEMS.jsonl')
    w('python3 scripts/f4/dropone.py RUN_DIR IDS.txt')
    w('python3 scripts/f4/summary.py RUN_DIR')
    w('```')
    w('')
    w('The runs and their parameters are recorded in the `tag`, `method`, `order`, `varorder` and `timeout` fields of')
    w('`logs/f4/lift.jsonl`. Several runs overlapped on the same cores (the smaller verified file is kept). The run')
    w('`sweep1` was stopped before its time limit, while 42 of its lifts (`lift/dp/canon`) were still running, after')
    w('about 21 to 24 minutes; those 42 lifts left no record, and each of their cores was attempted by the')
    w('other runs. HARDCELLS.txt lists the cells whose stored core had no certificate after the runs sweep1, sweep2_*,')
    w('hard9_* and pilot4_* (lines `class cell certid F` of the links); SYSTEMS.jsonl holds their initial systems,')
    w('taken from `exact6/c<N>/sec/p*.sec.jsonl` (the records with key `system`).')
    open(os.path.join(RUN, 'logs', 'f4', 'SUMMARY.md'), 'w').write('\n'.join(out) + '\n')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
