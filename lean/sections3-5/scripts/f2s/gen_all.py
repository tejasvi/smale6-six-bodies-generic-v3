#!/usr/bin/env python3
"""Writes L6Check/F2S/All.lean: per class, the keys of the cells of the specification search are keys of stored
lines (from the native_decide checks `f2s_c<k>` or `f2s_len_c<k>` and `f2s_c<k>_m<j>`, by `keys_whole` and
`keys_slices`), and the completeness theorem `f2s_cells_sound` for all 191 classes (Proposition 4.5: every pair of
complete trees with heights satisfying Lemma 4.3 and ell <= 0 for a representative is the key of a stored line).
Run from the package root after gen_checks.py. Usage: gen_all.py PREFIX_COUNTS"""
import sys
HEAVY = {3, 128, 148}
GROUP = 8
counts = {}
for line in open(sys.argv[1]):
    k, d, n = map(int, line.split())
    counts[k] = (d, n)
out = ['-- Generated by scripts/f2s/gen_all.py; do not edit.', 'import L6Check.F2S.Index', 'import L6Check.F2S.Order',
       'import L6Check.F2.CellsOf', 'import L6Sound.F2S.StoredSem', '',
       '/-! Proposition 4.5 from the specification search: every cell of the search is a stored cell (per class), and every',
       'pair of complete trees with heights satisfying the conditions of Lemma 4.3 and `ℓ(x) ≤ 0` for a representative is',
       'the key of a stored line of its class. -/', '', 'namespace L6.F2S.Checks', '', 'open L6.F2S', '']
for k in range(191):
    d, n = counts[k]
    if k not in HEAVY:
        out.append(f'theorem keys_c{k} : ∃ ks, storedKeys (L6.F2.Checks.cellsOf {k}) = some ks ∧ '
                   f'∀ c ∈ search keepLP (L6.F2.diagOf {k}), c.key ∈ ks := keys_whole f2s_c{k}')
    else:
        m = (n + GROUP - 1) // GROUP
        assert n == GROUP * m, (k, n)
        cases = ', '.join(f'f2s_c{k}_m{j}' for j in range(m))
        out.append(f'theorem keys_c{k} : ∃ ks, storedKeys (L6.F2.Checks.cellsOf {k}) = some ks ∧ '
                   f'∀ c ∈ search keepLP (L6.F2.diagOf {k}), c.key ∈ ks :=\n'
                   f'  keys_slices {m} (by decide) (by rw [f2s_len_c{k}]) (fun j hj => by\n'
                   f'    have hs : ∀ i : Fin {m}, checkBelow keepLP (L6.F2.diagOf {k}) {d} (L6.F2.Checks.cellsOf {k})\n'
                   f'        (((prefixPairs keepLP (L6.F2.diagOf {k}) {d}).drop (8 * i.1)).take 8) = true := by\n'
                   f'      intro i; fin_cases i\n' + ''.join(f'      · exact f2s_c{k}_m{j}\n' for j in range(m)) +
                   f'    exact hs ⟨j, hj⟩)')
    out.append('')
out.append('/-- Every cell of the specification search of every class has the key of a stored line of the class. -/')
out.append('theorem keys_all : ∀ k < 191, ∃ ks, storedKeys (L6.F2.Checks.cellsOf k) = some ks ∧')
out.append('    ∀ c ∈ search keepLP (L6.F2.diagOf k), c.key ∈ ks := by')
out.append('  intro k hk')
out.append('  match k, hk with')
for k in range(191):
    out.append(f'  | {k}, _ => exact keys_c{k}')
out.append('  | k + 191, h => exact absurd h (by omega)')
out.append('')
out.append('/-- **Proposition 4.5, completeness, for all 191 classes.** For the representative of a class, every pair of')
out.append('complete trees with heights satisfying the conditions of Lemma 4.3 and `ℓ(x) ≤ 0` (`Cond`) has the key of a stored')
out.append('line of the class: the same trees (as node sets, with the body on the leaf of `O`) and the same argmin sets. -/')
out.append('theorem f2s_cells_sound : ∀ k < 191, ∀ Xz Xw : ExpTree, Cond (L6.F2.diagOf k) Xz Xw →')
out.append('    ∃ line ∈ ((L6.F2.Checks.cellsOf k).splitOn "\\n").filter (· != ""),')
out.append('      keyOfLine line = some (Xz.T.key, Xw.T.key, argminString (L6.F2.diagOf k) Xz Xw) :=')
out.append('  fun k hk _ _ hX => cell_stored (keys_all k hk) (f2s_order k hk) hX')
out.append('')
out.append('end L6.F2S.Checks')
open('L6Check/F2S/All.lean', 'w').write('\n'.join(out) + '\n')
print('written')
