#!/usr/bin/env python3
"""Generates the Lean modules of the F2 checks (Proposition 4.5) from data/cells/parts.tsv and data/cells/SHA256SUMS.
Untrusted generator: every number it writes is re-checked by the Lean theorems (the chunk checks compare the Lean
search with the stored lines and the engine's counters; the tiling checks verify that the chunks cover the stored
files in the order of the engine's concatenation).

Per class k:
  L6Check/F2/Data/C<k>.lean   the stored list (include_str of data/cells/c<k>.jsonl) and its chunks
  L6Check/F2/C<k>.lean        SHA-256 of the stored list, tiling, the chunk checks (one evaluation for a light class),
                              and `class_c<k>`: every chunk passes and the chunks tile the list
  L6Check/F2/C<k>/K<j>.lean   one module per chunk of a heavy class
and L6Check/F2/All.lean: the index over the 191 classes, `f2_all`, the totals.
A class is light when its parts need at most LIM linear programs in the engine's run; the parts of a heavy class are
grouped, in the byte order of their file names, into chunks of at most LIM programs (a larger part is alone).
Usage (from the package root): gen_checks.py [LIM]"""
import collections, os, sys

LIM = int(sys.argv[1]) if len(sys.argv) > 1 else 2_000_000
rows = [l.rstrip('\n').split('\t') for l in open('data/cells/parts.tsv')][1:]
by = collections.defaultdict(dict)
for c, p, ln, lp, pr, fl in rows:
    assert fl == '0'
    by[int(c)][int(p)] = (int(ln), int(lp), int(pr))
sha = {}
for l in open('data/cells/SHA256SUMS'):
    h, n = l.split()
    sha[int(n[1:].split('.')[0])] = h
lex = sorted(range(384), key=lambda k: f'p{k}.jsonl')
HDR = '-- Generated by scripts/f2/gen_checks.py; do not edit.\n'


def chunks_of(c):
    tot = sum(by[c][p][1] for p in range(384))
    if tot <= LIM:
        return [lex], False
    out, cur, cl = [], [], 0
    for p in lex:
        lp = by[c][p][1]
        if cur and cl + lp > LIM:
            out.append(cur)
            cur, cl = [], 0
        cur.append(p)
        cl += lp
    out.append(cur)
    return out, True


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if not os.path.exists(path) or open(path).read() != text:
        open(path, 'w').write(text)


plan = {}
for c in range(191):
    chs, heavy = chunks_of(c)
    off = 0
    specs = []
    for ps in chs:
        cells = sum(by[c][p][0] for p in ps)
        lp = sum(by[c][p][1] for p in ps)
        pr = sum(by[c][p][2] for p in ps)
        pp = [by[c][p] for p in ps]
        specs.append((ps, off, cells, lp, pr, pp))
        off += cells
    plan[c] = (specs, heavy)
    # data module
    d = [HDR, 'import L6F2.Check\n\n',
         f'/-! The stored cell list of class {c} (`data/cells/c{c}.jsonl`) and its chunks. -/\n\n',
         'namespace L6.F2.Data\n\n',
         f'/-- The stored cell list of class {c}, byte for byte. -/\n',
         f'def cells_c{c} : String := include_str "../../../data/cells/c{c}.jsonl"\n\n']
    for j, (ps, off, cells, lp, pr, pp) in enumerate(specs):
        ppl = '[' + ', '.join(f'({a}, {b}, {e})' for a, b, e in pp) + ']'
        d.append(f'/-- Chunk {j} of class {c}. -/\n')
        d.append(f'def chunk_c{c}_{j} : L6.F2.Chunk :=\n  {{ cls := {c}, parts := {list(ps)}, off := {off}, cells := {cells}, '
                 f'lp := {lp}, pruned := {pr},\n    perPart := {ppl} }}\n\n')
    d.append(f'/-- The chunks of class {c}. -/\n')
    d.append(f'def chunks_c{c} : List L6.F2.Chunk := [{", ".join(f"chunk_c{c}_{j}" for j in range(len(specs)))}]\n\n')
    d.append('end L6.F2.Data\n')
    write(f'L6Check/F2/Data/C{c}.lean', ''.join(d))
    # chunk modules (heavy classes)
    if heavy:
        for j in range(len(specs)):
            write(f'L6Check/F2/C{c}/K{j}.lean',
                  HDR + f'import L6Check.F2.Data.C{c}\n\nnamespace L6.F2.Checks\n\n'
                  f'/-- The search reproduces chunk {j} of class {c} (cells, order, counters; no failure). -/\n'
                  f'theorem chunk_c{c}_{j} : L6.F2.checkChunk L6.F2.Data.cells_c{c} L6.F2.Data.chunk_c{c}_{j} = true := by\n'
                  f'  native_decide\n\nend L6.F2.Checks\n')
    # class module
    m = [HDR, f'import L6Check.F2.Data.C{c}\n']
    if heavy:
        m += [f'import L6Check.F2.C{c}.K{j}\n' for j in range(len(specs))]
    m += ['\nnamespace L6.F2.Checks\n\n',
          f'/-- The SHA-256 of the embedded stored list of class {c}. -/\n',
          f'theorem sha_c{c} : L6.SHA256.sha256Hex L6.F2.Data.cells_c{c} =\n    "{sha[c]}" := by\n  native_decide\n\n',
          f'/-- The chunks of class {c} cover the 384 parts in the order of the stored list. -/\n',
          f'theorem tiling_c{c} : L6.F2.tilingOk L6.F2.Data.cells_c{c} L6.F2.Data.chunks_c{c} {c} = true := by\n  native_decide\n\n']
    if heavy:
        names = ', '.join(f'chunk_c{c}_{j}' for j in range(len(specs)))
        m += [f'/-- Every chunk of class {c} passes. -/\n',
              f'theorem chunks_c{c} : L6.F2.Data.chunks_c{c}.all (L6.F2.checkChunk L6.F2.Data.cells_c{c}) = true := by\n',
              f'  simp only [L6.F2.Data.chunks_c{c}, List.all_cons, List.all_nil, {names}, Bool.and_true]\n\n']
    else:
        m += [f'/-- Every chunk of class {c} passes (one evaluation). -/\n',
              f'theorem chunks_c{c} : L6.F2.Data.chunks_c{c}.all (L6.F2.checkChunk L6.F2.Data.cells_c{c}) = true := by\n',
              f'  native_decide\n\n']
    m += [f'/-- Class {c}: the search reproduces the stored list, in order, with the engine\'s counters. -/\n',
          f'theorem class_c{c} : L6.F2.Data.chunks_c{c}.all (L6.F2.checkChunk L6.F2.Data.cells_c{c}) = true ∧\n'
          f'    L6.F2.tilingOk L6.F2.Data.cells_c{c} L6.F2.Data.chunks_c{c} {c} = true :=\n'
          f'  ⟨chunks_c{c}, tiling_c{c}⟩\n\nend L6.F2.Checks\n']
    write(f'L6Check/F2/C{c}.lean', ''.join(m))

# the stored cell lists (a module of their own, so that their users need not build the checks)
co = [HDR] + [f'import L6Check.F2.Data.C{c}\n' for c in range(191)]
co += ['\n/-! The stored cell list of each class (`data/cells/c<k>.jsonl`). -/\n\nnamespace L6.F2.Checks\n\n',
       '/-- The stored cell list of each class. -/\ndef cellsOf : Nat → String\n']
co += [f'  | {c} => L6.F2.Data.cells_c{c}\n' for c in range(191)]
co += ['  | _ => ""\n\nend L6.F2.Checks\n']
write('L6Check/F2/CellsOf.lean', ''.join(co))

# index and totals
a = [HDR] + [f'import L6Check.F2.C{c}\n' for c in range(191)] + ['import L6Check.F2.CellsOf\n']
a += ['\n/-! # Proposition 4.5: all 191 classes -/\n\nnamespace L6.F2.Checks\n\nopen L6.F2\n\n']
a += ['/-- The chunks of each class. -/\ndef chunksOf : Nat → List Chunk\n']
a += [f'  | {c} => L6.F2.Data.chunks_c{c}\n' for c in range(191)]
a += ['  | _ => []\n\n',
      '/-- **Proposition 4.5, the computation.** For each of the 191 classes, the replica of the engine\'s search (every\n'
      'prune by a linear program certified by `Farkas.check`, no failure) reproduces the stored cell list of the class,\n'
      'line by line and in order, with the engine\'s counts of linear programs and prunes, and the chunks cover the list. -/\n',
      'theorem f2_all : ∀ k, k < 191 → (chunksOf k).all (checkChunk (cellsOf k)) = true ∧\n'
      '    tilingOk (cellsOf k) (chunksOf k) k = true := by\n  intro k hk\n  match k, hk with\n']
a += [f'  | {c}, _ => exact class_c{c}\n' for c in range(191)]
a += ['  | k + 191, h => exact absurd h (by omega)\n\n',
      '/-- The totals over the 191 classes: cells, linear programs, prunes. -/\n',
      'theorem f2_totals : ((List.range 191).map fun k => totals (chunksOf k)).foldl\n'
      '    (fun (a, b, c) (x, y, z) => (a + x, b + y, c + z)) (0, 0, 0) = (91273, 133538490, 76087734) := by\n'
      '  native_decide\n\n',
      '/-- The number of classes with at least one cell. -/\n',
      'theorem f2_classes_with_cells : ((List.range 191).filter fun k => decide (0 < (totals (chunksOf k)).1)).length = 69 := by\n'
      '  native_decide\n\nend L6.F2.Checks\n']
write('L6Check/F2/All.lean', ''.join(a))
n_heavy = sum(1 for c in plan if plan[c][1])
n_chunks = sum(len(plan[c][0]) for c in plan)
print(f'LIM {LIM}: classes 191, heavy {n_heavy}, chunk evaluations {n_chunks}, chunk modules '
      f'{sum(len(plan[c][0]) for c in plan if plan[c][1])}')
