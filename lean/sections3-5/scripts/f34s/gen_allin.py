#!/usr/bin/env python3
"""Writes L6Check/F34S/AllIn.lean: the certificate list of each class (`certsOf_c<N>`, the concatenation of the lists
of its chunks; `certsOfClass`), the meaning of every cell of every class with the certificate drawn from that list
(`F34S_class_in_c<N>`, `class_meaning_in`), and `f34s_excluded_in`. Run from the package root after gen_allof.py
(untrusted: Lean checks what it writes)."""
import os, re
D = 'L6Check/F34S'
files = sorted((f for f in os.listdir(D) if re.fullmatch(r'C\d+K\d+\.lean', f)),
               key=lambda f: tuple(int(x) for x in re.findall(r'\d+', f)))
chunks = []
for f in files:
    t = open(os.path.join(D, f)).read()
    m = re.search(r'theorem F34S_c(\d+)_k(\d+) : checkChunkS (\d+) .*? open43\s*(\[.*?\])\s*(\d+) (\d+) \{', t, re.S)
    assert m, f
    cls, k, _, certs, lo, hi = m.groups()
    chunks.append((int(cls), int(k), int(lo), int(hi)))
cov = open('L6Check/F34/Cover.lean').read()
mm = re.search(r'theorem F34_cover : \[[^\]]*\] =\s*\[([\d,\s]*)\]', cov)
ncells = [int(x) for x in mm.group(1).replace('\n', ' ').split(',')]
names = [f'certs_c{c}_k{k}' for c, k, _, _ in chunks]
pos = {n: i for i, n in enumerate(names)}

def mem_proof(i):
    t = 'List.mem_cons_self'
    for _ in range(i):
        t = f'List.mem_cons_of_mem _ ({t})'
    return t

bycls = {}
for c, k, lo, hi in chunks:
    bycls.setdefault(c, []).append((k, lo, hi))
defs, classes = [], []
for c in range(191):
    cs = sorted(bycls.get(c, []))
    lists = [f'certs_c{c}_k{k}' for k, _, _ in cs]
    if lists:
        expr = lists[-1]
        for n in reversed(lists[:-1]):
            expr = f'{n} ++ ({expr})'
    else:
        expr = '[]'
    defs.append(f'/-- The certificates of the chunks of class {c} (appended to the right). -/\ndef certsOf_c{c} : List (String × String) :=\n  ' + expr)
    body = []
    J = len(cs)
    for jdx, (k, lo, hi) in enumerate(cs):
        n = f'certs_c{c}_k{k}'
        # membership of a text of chunk jdx in certsOf_c (right-nested appends)
        if J == 1:
            sub = 'hp'
        else:
            inner = 'hp' if jdx == J - 1 else 'List.mem_append.mpr (Or.inl hp)'
            for _ in range(jdx):
                inner = f'List.mem_append.mpr (Or.inr ({inner}))'
            sub = inner
        body.append(f'  by_cases h{k} : idx < {hi}\n'
                    f'  · rcases chunkS_meaningIn F34S_c{c}_k{k} (hcerts {n} ({mem_proof(pos[n])})) idx (by omega) h{k}'
                    f' with ho | hm\n'
                    f'    · exact Or.inl ho\n'
                    f'    · exact Or.inr fun Xz Xw hX hkey => claimMeaningIn_mono (fun p hp => {sub}) (hm Xz Xw hX hkey)')
    body.append('  omega')
    classes.append(f'''theorem F34S_class_in_c{c} (hcerts : AllChunkCertsMeaning) : ∀ idx, idx < {ncells[c]} →
    (L6.F34.openCells {c} open43).contains idx = true ∨
    ∀ Xz Xw : ExpTree, Cond (L6.F2.diagOf {c}) Xz Xw →
      keyOfLine (((L6.F2.Checks.cellsOf {c}).splitOn "\\n").toArray.getD idx "") =
        some (Xz.T.key, Xw.T.key, argminString (L6.F2.diagOf {c}) Xz Xw) →
      ClaimMeaningIn certsOf_c{c} Xz Xw := by
  intro idx hidx
  show _ ∨ ∀ Xz Xw : ExpTree, Cond (L6.F2.diagOf {c}) Xz Xw →
      keyOfLine ((L6.F2.Data.cells_c{c}.splitOn "\\n").toArray.getD idx "") =
        some (Xz.T.key, Xw.T.key, argminString (L6.F2.diagOf {c}) Xz Xw) → ClaimMeaningIn certsOf_c{c} Xz Xw
''' + '\n'.join(body) + '\n')
mcases = '\n'.join(f'  | {c} => certsOf_c{c}' for c in range(191))
cases = '\n'.join(f'  | {c}, _ => exact F34S_class_in_c{c} hcerts' for c in range(191))
txt = '-- Generated by scripts/f34s/gen_allin.py; do not edit.\n' + '''import L6Check.F34S.AllOf
import L6Sound.F34S.MeaningIn

/-! F3/F4 on the cells of the specification search, all classes, with the certificate of a core drawn from the
certificate list of its class (`certsOfClass k`): `f34s_excluded_in`. For the exclusion of a class at generic masses
this gives finitely many polynomials, fixed before the pair. -/

namespace L6.F34S.Checks

open L6.F34S L6.F2S L6.F34.Data

''' + '\n\n'.join(defs) + f'''

/-- The certificates of the chunks of each class (`[]` beyond the 191 classes). -/
def certsOfClass : Nat → List (String × String)
{mcases}
  | _ => []

''' + '\n'.join(classes) + f'''
/-- The meaning of every cell of every class, with the certificate drawn from the list of the class. -/
theorem class_meaning_in (hcerts : AllChunkCertsMeaning) : ∀ k < 191, ∀ idx, idx < ncellsList.getD k 0 →
    (L6.F34.openCells k open43).contains idx = true ∨
    ∀ Xz Xw : ExpTree, Cond (L6.F2.diagOf k) Xz Xw →
      keyOfLine (((L6.F2.Checks.cellsOf k).splitOn "\\n").toArray.getD idx "") =
        some (Xz.T.key, Xw.T.key, argminString (L6.F2.diagOf k) Xz Xw) →
      ClaimMeaningIn (certsOfClass k) Xz Xw := by
  intro k hk
  match k, hk with
{cases}
  | k + 191, h => exact absurd h (by omega)

/-- **F3/F4 for every pair satisfying `Cond`, with the certificates from the list of the class.** If every
certificate text of every chunk parses to a certificate with `CertMeaning`, then for every class `k < 191` and every
pair of complete trees with heights satisfying `Cond (diagOf k)`, `k` is one of the classes of the 43 open cells or
`ClaimMeaningIn (certsOfClass k)` holds: a single term, or a core with a certificate parsed from a text of the class's
list. -/
theorem f34s_excluded_in (hcerts : AllChunkCertsMeaning) : ∀ k < 191, ∀ Xz Xw : ExpTree,
    Cond (L6.F2.diagOf k) Xz Xw → k ∈ openClasses ∨ ClaimMeaningIn (certsOfClass k) Xz Xw := by
  intro k hk Xz Xw hX
  obtain ⟨line, hline, hkey⟩ := L6.F2S.Checks.f2s_cells_sound k hk Xz Xw hX
  have hl := List.all_eq_true.mp lines_ok k (List.mem_range.mpr hk)
  simp only [Bool.and_eq_true, beq_iff_eq] at hl
  obtain ⟨idx, hidx, hget⟩ := line_index hl.1 hl.2 hline
  rcases class_meaning_in hcerts k hk idx hidx with ho | hm
  · left
    have h2 := List.all_eq_true.mp open_ok k (List.mem_range.mpr hk)
    simp only [Bool.or_eq_true, List.isEmpty_iff, List.contains_iff_mem] at h2
    rcases h2 with h2 | h2
    · rw [h2] at ho
      exact absurd ho (by simp)
    · exact h2
  · right
    exact hm Xz Xw hX (by rw [hget]; exact hkey)

/-- `f34s_excluded_in` with the meaning of the certificates from their native checks. -/
theorem f34s_excluded_in_native : ∀ k < 191, ∀ Xz Xw : ExpTree,
    Cond (L6.F2.diagOf k) Xz Xw → k ∈ openClasses ∨ ClaimMeaningIn (certsOfClass k) Xz Xw :=
  f34s_excluded_in allChunkCertsMeaning_native

end L6.F34S.Checks
'''
open(os.path.join(D, 'AllIn.lean'), 'w').write(txt)
print('classes', len(classes))
