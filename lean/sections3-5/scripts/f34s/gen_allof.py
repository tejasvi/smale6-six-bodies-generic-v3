#!/usr/bin/env python3
"""Writes L6Check/F34S/CertLists.lean (the certificate lists of the chunk theorems `F34S_c<N>_k<k>` as named
constants, and the hypothesis `AllChunkCertsMeaning`: every certificate text of every chunk parses to a certificate
with `CertMeaning`) and L6Check/F34S/AllOf.lean (the meaning of every cell of every class from the chunk theorems and
that hypothesis, `F34S_class_of_c<N>`, `class_meaning_of`, and `f34s_excluded_of`; and `allChunkCertsMeaning_native`,
the hypothesis from the native certificate checks, so that `f34s_excluded_of` gives back `f34s_excluded`).
Run from the package root (untrusted: Lean checks what it writes)."""
import os, re
D = 'L6Check/F34S'
files = sorted((f for f in os.listdir(D) if re.fullmatch(r'C\d+K\d+\.lean', f)),
               key=lambda f: tuple(int(x) for x in re.findall(r'\d+', f)))
chunks, certimports = [], []
for f in files:
    t = open(os.path.join(D, f)).read()
    m = re.search(r'theorem F34S_c(\d+)_k(\d+) : checkChunkS (\d+) .*? open43\s*(\[.*?\])\s*(\d+) (\d+) \{', t, re.S)
    assert m, f
    cls, k, _, certs, lo, hi = m.groups()
    chunks.append((int(cls), int(k), certs, int(lo), int(hi)))
    for c in re.findall(r'^import (L6Check\.Certs\.C[0-9a-f]+)$', t, re.M):
        if c not in certimports:
            certimports.append(c)
cov = open('L6Check/F34/Cover.lean').read()
mm = re.search(r'theorem F34_cover : \[[^\]]*\] =\s*\[([\d,\s]*)\]', cov)
ncells = [int(x) for x in mm.group(1).replace('\n', ' ').split(',')]
names = [f'certs_c{c}_k{k}' for c, k, _, _, _ in chunks]
pos = {n: i for i, n in enumerate(names)}

def mem_proof(i):
    t = 'List.mem_cons_self'
    for _ in range(i):
        t = f'List.mem_cons_of_mem _ ({t})'
    return t

defs = '\n\n'.join(f'/-- The certificates of the chunk {k} of class {c}. -/\ndef certs_c{c}_k{k} : List (String × String) :=\n  {certs}'
                   for c, k, certs, _, _ in chunks)
certlists = '-- Generated by scripts/f34s/gen_allof.py; do not edit.\n' + '\n'.join(f'import {c}' for c in certimports) + \
    '\nimport L6Sound.Poly.Sound\n' + f'''
/-! The certificate lists of the chunks of F3/F4 on the cells of the specification search, as named constants, and
the hypothesis that all of them have their meaning. -/

namespace L6.F34S.Checks

/-- The certificate texts of a list parse to certificates with `CertMeaning`. -/
def CertsMeaning (l : List (String × String)) : Prop :=
  ∀ p ∈ l, ∃ c, L6.Poly.parseCert p.2 = some c ∧ L6.Poly.CertMeaning c

{defs}

/-- The certificate lists of the {len(names)} chunks. -/
def chunkCertLists : List (List (String × String)) :=
  [{", ".join(names)}]

/-- Every certificate text of every chunk parses to a certificate with `CertMeaning`. -/
def AllChunkCertsMeaning : Prop := ∀ l ∈ chunkCertLists, CertsMeaning l

end L6.F34S.Checks
'''
open(os.path.join(D, 'CertLists.lean'), 'w').write(certlists)

bycls = {}
for c, k, certs, lo, hi in chunks:
    bycls.setdefault(c, []).append((k, lo, hi))
classes = []
for c in range(191):
    body = []
    for k, lo, hi in sorted(bycls.get(c, [])):
        n = f'certs_c{c}_k{k}'
        body.append(f'  by_cases h{k} : idx < {hi}\n'
                    f'  · exact chunkS_meaning_of F34S_c{c}_k{k} (hcerts {n} ({mem_proof(pos[n])})) idx (by omega) h{k}')
    body.append('  omega')
    classes.append(f'''theorem F34S_class_of_c{c} (hcerts : AllChunkCertsMeaning) : ∀ idx, idx < {ncells[c]} →
    (L6.F34.openCells {c} open43).contains idx = true ∨
    ∀ Xz Xw : ExpTree, Cond (L6.F2.diagOf {c}) Xz Xw →
      keyOfLine (((L6.F2.Checks.cellsOf {c}).splitOn "\\n").toArray.getD idx "") =
        some (Xz.T.key, Xw.T.key, argminString (L6.F2.diagOf {c}) Xz Xw) →
      ClaimMeaning Xz Xw := by
  intro idx hidx
  show _ ∨ ∀ Xz Xw : ExpTree, Cond (L6.F2.diagOf {c}) Xz Xw →
      keyOfLine ((L6.F2.Data.cells_c{c}.splitOn "\\n").toArray.getD idx "") =
        some (Xz.T.key, Xw.T.key, argminString (L6.F2.diagOf {c}) Xz Xw) → ClaimMeaning Xz Xw
''' + '\n'.join(body) + '\n')
cases = '\n'.join(f'  | {c}, _ => exact F34S_class_of_c{c} hcerts' for c in range(191))
pat = ' | '.join(['rfl'] * len(names))
natcases = '\n'.join(f'  · exact fun p hp => (L6.Poly.checkCert_meaning (L6.F34.Checks.certsOK_c{c}_k{k} p hp))'
                     for c, k, _, _, _ in chunks)
allof = '-- Generated by scripts/f34s/gen_allof.py; do not edit.\n' + '''import L6Check.F34S.All
import L6Check.F34S.CertLists
import L6Sound.F34S.MeaningOf

/-! F3/F4 on the cells of the specification search, all classes, with the meaning of the certificates as a
hypothesis (`AllChunkCertsMeaning`): `f34s_excluded_of`. With the meaning given by the native certificate checks
(`allChunkCertsMeaning_native`) it is `f34s_excluded`; it can also be given by checks of the certificates in the
kernel. -/

namespace L6.F34S.Checks

open L6.F34S L6.F2S L6.F34.Data

''' + '\n'.join(classes) + f'''
/-- The meaning of every cell of every class, from the meaning of the certificates. -/
theorem class_meaning_of (hcerts : AllChunkCertsMeaning) : ∀ k < 191, ∀ idx, idx < ncellsList.getD k 0 →
    (L6.F34.openCells k open43).contains idx = true ∨
    ∀ Xz Xw : ExpTree, Cond (L6.F2.diagOf k) Xz Xw →
      keyOfLine (((L6.F2.Checks.cellsOf k).splitOn "\\n").toArray.getD idx "") =
        some (Xz.T.key, Xw.T.key, argminString (L6.F2.diagOf k) Xz Xw) →
      ClaimMeaning Xz Xw := by
  intro k hk
  match k, hk with
{cases}
  | k + 191, h => exact absurd h (by omega)

/-- **F3/F4 for every pair satisfying `Cond`, from the meaning of the certificates.** If every certificate text of
every chunk parses to a certificate with `CertMeaning`, then for every class `k < 191` and every pair of complete
trees with heights satisfying `Cond (diagOf k)`, `k` is one of the classes of the 43 open cells or `ClaimMeaning`
holds. -/
theorem f34s_excluded_of (hcerts : AllChunkCertsMeaning) : ∀ k < 191, ∀ Xz Xw : ExpTree,
    Cond (L6.F2.diagOf k) Xz Xw → k ∈ openClasses ∨ ClaimMeaning Xz Xw := by
  intro k hk Xz Xw hX
  obtain ⟨line, hline, hkey⟩ := L6.F2S.Checks.f2s_cells_sound k hk Xz Xw hX
  have hl := List.all_eq_true.mp lines_ok k (List.mem_range.mpr hk)
  simp only [Bool.and_eq_true, beq_iff_eq] at hl
  obtain ⟨idx, hidx, hget⟩ := line_index hl.1 hl.2 hline
  rcases class_meaning_of hcerts k hk idx hidx with ho | hm
  · left
    have h2 := List.all_eq_true.mp open_ok k (List.mem_range.mpr hk)
    simp only [Bool.or_eq_true, List.isEmpty_iff, List.contains_iff_mem] at h2
    rcases h2 with h2 | h2
    · rw [h2] at ho
      exact absurd ho (by simp)
    · exact h2
  · right
    exact hm Xz Xw hX (by rw [hget]; exact hkey)

/-- The meaning of the certificates from their native checks (`certsOK_c<N>_k<k>` and `checkCert_meaning`). -/
theorem allChunkCertsMeaning_native : AllChunkCertsMeaning := by
  intro l hl
  simp only [chunkCertLists, List.mem_cons, List.not_mem_nil, or_false] at hl
  rcases hl with {pat}
{natcases}

end L6.F34S.Checks
'''
open(os.path.join(D, 'AllOf.lean'), 'w').write(allof)
print('chunks', len(chunks), 'cert imports', len(certimports))
