#!/usr/bin/env python3
"""Writes L6Check/F34S/All.lean: from the chunk theorems `F34S_c<N>_k<k>` (L6Check/F34S/C<N>K<k>.lean) and the
certificate theorems `certsOK_c<N>_k<k>` of F3/F4, the meaning of every cell of every class (`F34S_class_c<N>`), and
with `f2s_cells_sound` the theorem `f34s_excluded`: every pair of complete trees with heights satisfying `Cond` for a
class representative lies in an open class or satisfies `ClaimMeaning`. Run from the package root (untrusted: Lean
checks what it writes)."""
import os, re
D = 'L6Check/F34S'
files = sorted((f for f in os.listdir(D) if re.fullmatch(r'C\d+K\d+\.lean', f)),
               key=lambda f: tuple(int(x) for x in re.findall(r'\d+', f)))
chunks = {}
for f in files:
    t = open(os.path.join(D, f)).read()
    m = re.search(r'theorem F34S_c(\d+)_k(\d+) : checkChunkS (\d+) .*?\]\s*(\d+) (\d+) \{', t, re.S)
    assert m, f
    cls, k, _, lo, hi = map(int, m.groups())
    chunks.setdefault(cls, []).append((k, lo, hi))
cov = open('L6Check/F34/Cover.lean').read()
mm = re.search(r'theorem F34_cover : \[[^\]]*\] =\s*\[([\d,\s]*)\]', cov)
ncells = [int(x) for x in mm.group(1).replace('\n', ' ').split(',')]
assert len(ncells) == 191
for c in range(191):
    cs = sorted(chunks.get(c, []))
    pos = 0
    for k, lo, hi in cs:
        assert lo == pos, (c, k)
        pos = hi
    assert pos == ncells[c], (c, pos, ncells[c])
imports = [f'import L6Check.F34S.{f[:-5]}' for f in files] + \
          [f'import L6Check.F34.CertsOK.{f[:-5]}' for f in files] + \
          ['import L6Sound.F34S.Meaning', 'import L6Check.F2S.All']
classes = []
for c in range(191):
    cs = sorted(chunks.get(c, []))
    body = []
    for k, lo, hi in cs:
        body.append(f'  by_cases h{k} : idx < {hi}\n'
                    f'  · exact chunkS_meaning F34S_c{c}_k{k} L6.F34.Checks.certsOK_c{c}_k{k} idx (by omega) h{k}')
    body.append('  omega')
    classes.append(f'''theorem F34S_class_c{c} : ∀ idx, idx < {ncells[c]} →
    (L6.F34.openCells {c} open43).contains idx = true ∨
    ∀ Xz Xw : ExpTree, Cond (L6.F2.diagOf {c}) Xz Xw →
      keyOfLine (((L6.F2.Checks.cellsOf {c}).splitOn "\\n").toArray.getD idx "") =
        some (Xz.T.key, Xw.T.key, argminString (L6.F2.diagOf {c}) Xz Xw) →
      ClaimMeaning Xz Xw := by
  intro idx hidx
  show _ ∨ ∀ Xz Xw : ExpTree, Cond (L6.F2.diagOf {c}) Xz Xw →
      keyOfLine ((L6.F2.Data.cells_c{c}.splitOn "\\n").toArray.getD idx "") =
        some (Xz.T.key, Xw.T.key, argminString (L6.F2.diagOf {c}) Xz Xw) → ClaimMeaning Xz Xw
''' + '\n'.join(body) + '\n')
cases = '\n'.join(f'  | {c}, _ => exact F34S_class_c{c}' for c in range(191))
nl = ', '.join(str(x) for x in ncells)
txt = '-- Generated by scripts/f34s/gen_all.py; do not edit.\n' + '\n'.join(imports) + f'''

/-! F3/F4 on the cells of the specification search, all classes: the meaning of the cells of each class from its
chunk theorems, and with the completeness of Proposition 4.5 (`f2s_cells_sound`) the exclusion statement
`f34s_excluded`. -/

namespace L6.F34S.Checks

open L6.F34S L6.F2S L6.F34.Data

{chr(10).join(classes)}
/-- The numbers of cells of the classes. -/
def ncellsList : List Nat := [{nl}]

/-- The cell list of each class ends with a newline after its last line (so its lines are the entries of
`splitOn "\\n"` but the last). -/
theorem lines_ok : (List.range 191).all (fun k => ((L6.F2.Checks.cellsOf k).splitOn "\\n").length ==
    ncellsList.getD k 0 + 1 && ((L6.F2.Checks.cellsOf k).splitOn "\\n").getLast? == some "") = true := by
  native_decide

/-- The 43 open cells lie in the classes `openClasses`. -/
theorem open_ok : (List.range 191).all (fun k => (L6.F34.openCells k open43).isEmpty || openClasses.contains k) =
    true := by
  native_decide

/-- The meaning of every cell of every class. -/
theorem class_meaning : ∀ k < 191, ∀ idx, idx < ncellsList.getD k 0 →
    (L6.F34.openCells k open43).contains idx = true ∨
    ∀ Xz Xw : ExpTree, Cond (L6.F2.diagOf k) Xz Xw →
      keyOfLine (((L6.F2.Checks.cellsOf k).splitOn "\\n").toArray.getD idx "") =
        some (Xz.T.key, Xw.T.key, argminString (L6.F2.diagOf k) Xz Xw) →
      ClaimMeaning Xz Xw := by
  intro k hk
  match k, hk with
{cases}
  | k + 191, h => exact absurd h (by omega)

theorem line_index {{txt line : String}} {{n : Nat}} (hlen : (txt.splitOn "\\n").length = n + 1)
    (hlast : (txt.splitOn "\\n").getLast? = some "") (hline : line ∈ (txt.splitOn "\\n").filter (· != "")) :
    ∃ idx, idx < n ∧ (txt.splitOn "\\n").toArray.getD idx "" = line := by
  obtain ⟨hmem, hne⟩ := List.mem_filter.mp hline
  obtain ⟨i, hi, hget⟩ := List.mem_iff_getElem.mp hmem
  refine ⟨i, ?_, ?_⟩
  · rcases Nat.lt_or_ge i n with h | h
    · exact h
    · have hin : i = n := by omega
      subst hin
      rw [List.getLast?_eq_getElem?, hlen, Nat.add_sub_cancel, List.getElem?_eq_getElem hi, hget] at hlast
      simp only [Option.some.injEq] at hlast
      rw [hlast] at hne
      exact absurd hne (by decide)
  · rw [Array.getD_eq_getD_getElem?, List.getElem?_toArray, List.getElem?_eq_getElem hi, hget]
    rfl

/-- **F3/F4 for every pair satisfying `Cond`.** For every class `k < 191` and every pair of complete trees with
heights satisfying `Cond (diagOf k)`, either `k` is one of the classes of the 43 open cells (the seven diagrams of
Sections 6 and 7), or `ClaimMeaning` holds: a good identity with a term of strictly least exponent (Lemma 5.1), or a
core with a cofactor certificate (Lemma 5.2). -/
theorem f34s_excluded : ∀ k < 191, ∀ Xz Xw : ExpTree, Cond (L6.F2.diagOf k) Xz Xw →
    k ∈ openClasses ∨ ClaimMeaning Xz Xw := by
  intro k hk Xz Xw hX
  obtain ⟨line, hline, hkey⟩ := L6.F2S.Checks.f2s_cells_sound k hk Xz Xw hX
  have hl := List.all_eq_true.mp lines_ok k (List.mem_range.mpr hk)
  simp only [Bool.and_eq_true, beq_iff_eq] at hl
  obtain ⟨idx, hidx, hget⟩ := line_index hl.1 hl.2 hline
  rcases class_meaning k hk idx hidx with ho | hm
  · left
    have h2 := List.all_eq_true.mp open_ok k (List.mem_range.mpr hk)
    simp only [Bool.or_eq_true, List.isEmpty_iff, List.contains_iff_mem] at h2
    rcases h2 with h2 | h2
    · rw [h2] at ho
      exact absurd ho (by simp)
    · exact h2
  · right
    exact hm Xz Xw hX (by rw [hget]; exact hkey)

end L6.F34S.Checks
'''
open(os.path.join(D, 'All.lean'), 'w').write(txt)
print('classes', len(classes), 'chunks', len(files))
